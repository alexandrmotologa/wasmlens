"""Export WebAssembly module interfaces to standard C/C++ header files (.h)."""

from __future__ import annotations

import re
from typing import Optional

from wasmlens.parser.types import ExternalKind, ValueType, WasmModule


def valtype_to_c(v: ValueType) -> str:
    """Map WebAssembly ValueType to corresponding C stdint type."""
    mapping = {
        ValueType.I32: "int32_t",
        ValueType.I64: "int64_t",
        ValueType.F32: "float",
        ValueType.F64: "double",
    }
    return mapping.get(v, "void*")


def sanitize_identifier(name: str) -> str:
    """Sanitize arbitrary string into valid C identifier."""
    clean = re.sub(r"[^a-zA-Z0-9_]", "_", name)
    if clean and clean[0].isdigit():
        clean = "_" + clean
    return clean or "unnamed"


def generate_c_header(
    module: WasmModule,
    module_name: Optional[str] = "wasm_module",
    header_guard: Optional[str] = None,
) -> str:
    """Generate self-contained C header with prototypes for exported and imported symbols."""
    guard = header_guard or f"WASMLENS_{sanitize_identifier(module_name).upper()}_H"
    lines = [
        f"/* Generated by WasmLens C Header Exporter */",
        f"/* Module: {module_name} | WebAssembly 2.0 */",
        f"",
        f"#ifndef {guard}",
        f"#define {guard}",
        f"",
        f"#include <stdint.h>",
        f"#include <stdbool.h>",
        f"",
        "#ifdef __cplusplus",
        'extern "C" {',
        "#endif",
        f"",
        f"/* Linear Memory Configuration */",
    ]

    if module.memories:
        mem = module.memories[0]
        max_str = str(mem.limits.max) if mem.limits.max is not None else "UNLIMITED"
        lines.append(f"#define WASM_MEMORY_PAGE_SIZE 65536")
        lines.append(f"#define WASM_MEMORY_INITIAL_PAGES {mem.limits.min}")
        lines.append(f"#define WASM_MEMORY_MAX_PAGES {max_str}")
        lines.append("")

    # Imports
    imports_fn = [imp for imp in module.imports if imp.kind == ExternalKind.FUNCTION]
    if imports_fn:
        lines.append("/* Imported Host Functions */")
        for imp in imports_fn:
            sig = module.types[imp.type_idx]
            ret_type = valtype_to_c(sig.results[0]) if sig.results else "void"
            params = [f"{valtype_to_c(p)} arg{i}" for i, p in enumerate(sig.params)] or ["void"]
            fn_id = sanitize_identifier(f"{imp.module}_{imp.field}")
            lines.append(f"extern {ret_type} {fn_id}({', '.join(params)});")
        lines.append("")

    # Exports
    exports_fn = [exp for exp in module.exports if exp.kind == ExternalKind.FUNCTION]
    if exports_fn:
        lines.append("/* Exported WebAssembly Functions */")
        for exp in exports_fn:
            sig = module.get_function_type(exp.index)
            ret_type = valtype_to_c(sig.results[0]) if sig.results else "void"
            params = [f"{valtype_to_c(p)} arg{i}" for i, p in enumerate(sig.params)] or ["void"]
            fn_id = sanitize_identifier(exp.name)
            lines.append(f"{ret_type} {fn_id}({', '.join(params)});")
        lines.append("")

    # Globals
    if module.globals:
        lines.append("/* Exported or Internal Globals */")
        for i, g in enumerate(module.globals):
            t = valtype_to_c(g.type.valtype)
            mut_str = "/* mutable */ " if g.type.mutable else "/* const */ "
            lines.append(f"extern {mut_str}{t} wasm_global_{i};")
        lines.append("")

    lines.extend([
        "#ifdef __cplusplus",
        "}",
        "#endif",
        f"",
        f"#endif /* {guard} */",
        f"",
    ])

    return "\n".join(lines)
